def normalize_report_type(report_type: str) -> str:
    if report_type in REPORT_TYPE_CONFIG:
        return report_type
    return "股票分析报告"


def report_type_slug(report_type: str) -> str:
    return REPORT_TYPE_CONFIG[normalize_report_type(report_type)]["slug"]


def infer_sector(stock_code: str) -> str:
    normalized = (stock_code or "").upper()
    if normalized.startswith(("600", "601", "603", "605")):
        return "主板"
    if normalized.startswith("688"):
        return "科创板"
    if normalized.startswith("300"):
        return "创业板"
    if normalized.startswith(("000", "001", "002", "003")):
        return "深市主板"
    if normalized.startswith("8"):
        return "北交所"
    return "未知板块"


def clean_markdown_output(text: str) -> str:
    """去掉模型输出中包裹的 ```markdown 围栏。"""
    cleaned = (text or "").strip()
    if cleaned.startswith("```markdown"):
        cleaned = cleaned[len("```markdown") :].strip()
    elif cleaned.startswith("```md"):
        cleaned = cleaned[len("```md") :].strip()
    elif cleaned.startswith("```"):
        cleaned = cleaned[len("```") :].strip()
    if cleaned.endswith("```"):
        cleaned = cleaned[:-3].strip()
    return cleaned


def get_report_filename(stock_code: str, stock_name: str, report_type: str) -> str:
    slug = report_type_slug(report_type)
    return f"{stock_code}_{stock_name}_{slug}.md"
